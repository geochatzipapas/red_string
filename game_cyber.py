def _place(case, target):
    """Μετακινεί τον ένοχο σε άλλη θέση της λίστας, ώστε να μην είναι πάντα στην ίδια."""
    c = case["culprit"]
    if c == target:
        return
    s = case["suspects"]
    s[c], s[target] = s[target], s[c]
    for q in case["interro"]:
        if q["s"] == c:
            q["s"] = target
        elif q["s"] == target:
            q["s"] = c
    case["culprit"] = target


for _case, _t in zip(CASES, [1, 3, 0, 2, 4]):
    _place(_case, _t)

